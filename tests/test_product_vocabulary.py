"""Product-string matching: the cheapest place for the shortlist to go wrong.

Every case here is a real annotation string. The lists are in decision_rules.yaml;
these tests only pin how the code applies them.
"""
import pytest

from rbpfinder.evidence import normalize
from rbpfinder.nominate import c1_context, c2_keywords

_C1 = "stage1.channels.C1_module_position"


def _c1_kind(product, rules):
    return c1_context._classify(
        product,
        rules.get(_C1 + ".anchors_strong"),
        rules.get(_C1 + ".anchors_weak"),
        rules.get(_C1 + ".anchors_boundary"),
        rules.get("stage2.annotation_term_map.token_match_terms"),
    )


@pytest.mark.parametrize("product", [
    "metallopeptidase",
    "metal-dependent phosphohydrolase",
    "catalytic subunit",
    "crystallin-like protein",
    "RNA editing protein",
    "conditional lethal protein",
])
def test_tal_dit_inside_a_word_is_not_a_tail_anchor(product, rules):
    assert _c1_kind(product, rules) is None


@pytest.mark.parametrize("product,kind", [
    ("distal tail protein Dit", "strong"),
    ("tail-associated lysin (Tal)", "strong"),
    ("baseplate-Tal", "strong"),
    ("Dit/Tal fusion", "strong"),
    ("tail length tape measure protein", "strong"),
    ("tail fiber protein", "strong"),
    ("tail protein", "weak"),
    ("portal protein", "boundary"),
])
def test_real_anchors_still_anchor(product, kind, rules):
    assert _c1_kind(product, rules) == kind


def test_c1_opens_no_window_on_a_replication_module(rules):
    products = ["DNA ligase", "metallopeptidase", "catalytic subunit",
                "RNA editing protein", "hypothetical protein"]
    rows = [{"cds_id": "X_CDS_%04d" % i, "product": p,
             "start_nt": i * 1000 + 1, "end_nt": i * 1000 + 900}
            for i, p in enumerate(products, 1)]
    out = c1_context.run(rows, rules)
    assert out["nominated"] == set()
    assert out["warning"]


def test_c2_does_not_nominate_portal_via_tal(rules):
    rows = [{"cds_id": "a", "product": "portal protein"},
            {"cds_id": "b", "product": "catalytic subunit"},
            {"cds_id": "c", "product": "RNA editing protein"},
            {"cds_id": "d", "product": "tail-associated lysin (Tal)"},
            {"cds_id": "e", "product": "tail fiber protein"},
            {"cds_id": "f", "product": "metallopeptidase"}]
    out = c2_keywords.run(rows, rules)
    # f stays nominated: `peptidase` is a deliberate recall keyword, not the Tal bug.
    assert out["nominated"] == {"d", "e", "f"}
    assert out["matches"]["f"]["terms"] == ["peptidase"]


@pytest.mark.parametrize("product", [
    "tail fiber assembly protein",
    "tail fibre assembly protein",
    "tail fiber chaperone",
    "tail assembly chaperone",
    "tail spike assembly chaperone",
])
def test_helper_head_noun_is_not_receptor_binding(product, rules):
    """`compound_title_helper`: T4 P03739 / lambda P03740 are chaperones, not fibres."""
    assert normalize._direction(product, rules) == "supports_structural_only"


@pytest.mark.parametrize("product,direction", [
    ("tail fiber protein", "supports_receptor_binding"),
    ("tail spike protein", "supports_receptor_binding"),
    ("receptor binding protein", "supports_receptor_binding"),
    # explicit claim outranks a co-occurring structural word (N4 gp65)
    ("tail sheath and receptor binding protein", "supports_receptor_binding"),
    ("tail protein", "supports_structural_only"),
    ("baseplate protein", "supports_structural_only"),
    ("portal protein", "supports_non_rbp_identity"),
    # `glycosyl` inside `glycosylase` must not read as glycan-active (T5 CDS_0017)
    ("endonuclease nicking abasic sites generated by host uracil glycosylase Ung",
     "supports_non_rbp_identity"),
    ("hypothetical protein", "uninformative"),
])
def test_direction_of_established_cases(product, direction, rules):
    assert normalize._direction(product, rules) == direction
